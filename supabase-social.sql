-- Lootora social systems: guilds and server-resolved asynchronous PvP.
-- Run once in Supabase SQL Editor after supabase-clicker.sql.

create table if not exists public.lootora_guilds (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create unique index if not exists lootora_guilds_name_lower_uidx on public.lootora_guilds (lower(name));
create table if not exists public.lootora_guild_members (
  guild_id bigint not null references public.lootora_guilds(id) on delete cascade,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('leader','member')),
  joined_at timestamptz not null default now(),
  primary key (guild_id,user_id)
);
create index if not exists lootora_guild_members_guild_idx on public.lootora_guild_members(guild_id);

alter table public.lootora_guilds enable row level security;
alter table public.lootora_guild_members enable row level security;
drop policy if exists "Authenticated players can discover guilds" on public.lootora_guilds;
create policy "Authenticated players can discover guilds" on public.lootora_guilds
for select to authenticated using (true);
drop policy if exists "Authenticated players can view guild membership" on public.lootora_guild_members;
create policy "Authenticated players can view guild membership" on public.lootora_guild_members
for select to authenticated using (true);
grant select on public.lootora_guilds, public.lootora_guild_members to authenticated;

create or replace function public.lootora_create_guild(p_name text, p_description text default '')
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_uid uuid := auth.uid();
  v_name text := btrim(coalesce(p_name,''));
  v_description text := btrim(coalesce(p_description,''));
  v_id bigint;
begin
  if v_uid is null then raise exception 'Войди в аккаунт'; end if;
  if char_length(v_name) < 3 or char_length(v_name) > 24 then raise exception 'Название должно содержать от 3 до 24 символов'; end if;
  if char_length(v_description) > 160 then raise exception 'Описание не должно превышать 160 символов'; end if;
  if exists(select 1 from public.lootora_guild_members where user_id=v_uid) then raise exception 'Ты уже состоишь в гильдии'; end if;
  insert into public.lootora_guilds(name,description,owner_id) values(v_name,v_description,v_uid) returning id into v_id;
  insert into public.lootora_guild_members(guild_id,user_id,role) values(v_id,v_uid,'leader');
  return jsonb_build_object('id',v_id,'name',v_name,'description',v_description,'members',1,'role','leader');
exception when unique_violation then
  raise exception 'Гильдия с таким названием уже существует';
end;
$$;

create or replace function public.lootora_join_guild(p_guild_id bigint)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_uid uuid := auth.uid();
  v_name text;
  v_count integer;
begin
  if v_uid is null then raise exception 'Войди в аккаунт'; end if;
  if exists(select 1 from public.lootora_guild_members where user_id=v_uid) then raise exception 'Сначала покинь текущую гильдию'; end if;
  select name into v_name from public.lootora_guilds where id=p_guild_id for update;
  if not found then raise exception 'Гильдия не найдена'; end if;
  select count(*) into v_count from public.lootora_guild_members where guild_id=p_guild_id;
  if v_count >= 30 then raise exception 'В гильдии уже 30 участников'; end if;
  insert into public.lootora_guild_members(guild_id,user_id,role) values(p_guild_id,v_uid,'member');
  return jsonb_build_object('id',p_guild_id,'name',v_name,'members',v_count+1,'role','member');
end;
$$;

create or replace function public.lootora_leave_guild()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_uid uuid := auth.uid();
  v_guild_id bigint;
  v_role text;
begin
  if v_uid is null then raise exception 'Войди в аккаунт'; end if;
  select guild_id,role into v_guild_id,v_role from public.lootora_guild_members where user_id=v_uid;
  if not found then raise exception 'Ты не состоишь в гильдии'; end if;
  if v_role='leader' then
    if exists(select 1 from public.lootora_guild_members where guild_id=v_guild_id and user_id<>v_uid) then
      raise exception 'Передай лидерство или распусти гильдию';
    end if;
    delete from public.lootora_guilds where id=v_guild_id;
  else
    delete from public.lootora_guild_members where guild_id=v_guild_id and user_id=v_uid;
  end if;
  return jsonb_build_object('left',true);
end;
$$;

create or replace function public.lootora_disband_guild()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_uid uuid := auth.uid(); v_id bigint;
begin
  if v_uid is null then raise exception 'Войди в аккаунт'; end if;
  select id into v_id from public.lootora_guilds where owner_id=v_uid;
  if not found then raise exception 'Распустить гильдию может только лидер'; end if;
  delete from public.lootora_guilds where id=v_id;
  return jsonb_build_object('disbanded',true);
end;
$$;

create table if not exists public.lootora_pvp_stats (
  user_id uuid primary key references auth.users(id) on delete cascade,
  rating integer not null default 1000 check (rating >= 0),
  wins integer not null default 0 check (wins >= 0),
  losses integer not null default 0 check (losses >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.lootora_pvp_queue (
  user_id uuid primary key references auth.users(id) on delete cascade,
  queued_at timestamptz not null default now()
);
create table if not exists public.lootora_pvp_matches (
  id bigint generated by default as identity primary key,
  player_a uuid not null references auth.users(id) on delete cascade,
  player_b uuid not null references auth.users(id) on delete cascade,
  winner_id uuid not null references auth.users(id) on delete cascade,
  rating_a_before integer not null,
  rating_b_before integer not null,
  created_at timestamptz not null default now(),
  check (player_a <> player_b),
  check (winner_id=player_a or winner_id=player_b)
);
create index if not exists lootora_pvp_matches_created_idx on public.lootora_pvp_matches(created_at desc);
alter table public.lootora_pvp_stats enable row level security;
alter table public.lootora_pvp_queue enable row level security;
alter table public.lootora_pvp_matches enable row level security;
drop policy if exists "Players can view public PvP ratings" on public.lootora_pvp_stats;
create policy "Players can view public PvP ratings" on public.lootora_pvp_stats for select to authenticated using (true);
drop policy if exists "Players can view their PvP matches" on public.lootora_pvp_matches;
create policy "Players can view their PvP matches" on public.lootora_pvp_matches for select to authenticated using (auth.uid()=player_a or auth.uid()=player_b);
grant select on public.lootora_pvp_stats, public.lootora_pvp_matches to authenticated;

create or replace function public.lootora_pvp_join_queue()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_uid uuid := auth.uid();
  v_opponent uuid;
  v_rating integer;
  v_opponent_rating integer;
  v_probability numeric;
  v_winner uuid;
  v_username text;
  v_match_id bigint;
begin
  if v_uid is null then raise exception 'Войди в аккаунт'; end if;
  delete from public.lootora_pvp_queue where queued_at < now()-interval '10 minutes';
  insert into public.lootora_pvp_stats(user_id) values(v_uid) on conflict(user_id) do nothing;
  insert into public.lootora_pvp_queue(user_id,queued_at) values(v_uid,now())
  on conflict(user_id) do update set queued_at=excluded.queued_at;
  select user_id into v_opponent from public.lootora_pvp_queue
  where user_id<>v_uid order by queued_at asc limit 1 for update skip locked;
  if v_opponent is null then
    return jsonb_build_object('status','queued','message','Ищем соперника. Повтори поиск через несколько секунд.');
  end if;
  delete from public.lootora_pvp_queue where user_id in (v_uid,v_opponent);
  insert into public.lootora_pvp_stats(user_id) values(v_opponent) on conflict(user_id) do nothing;
  select rating into v_rating from public.lootora_pvp_stats where user_id=v_uid for update;
  select rating into v_opponent_rating from public.lootora_pvp_stats where user_id=v_opponent for update;
  v_probability := 1.0/(1.0+power(10.0,(v_opponent_rating-v_rating)::numeric/400.0));
  v_winner := case when random()<v_probability then v_uid else v_opponent end;
  insert into public.lootora_pvp_matches(player_a,player_b,winner_id,rating_a_before,rating_b_before)
  values(v_uid,v_opponent,v_winner,v_rating,v_opponent_rating) returning id into v_match_id;
  if v_winner=v_uid then
    update public.lootora_pvp_stats set rating=rating+16,wins=wins+1,updated_at=now() where user_id=v_uid;
    update public.lootora_pvp_stats set rating=greatest(0,rating-16),losses=losses+1,updated_at=now() where user_id=v_opponent;
  else
    update public.lootora_pvp_stats set rating=greatest(0,rating-16),losses=losses+1,updated_at=now() where user_id=v_uid;
    update public.lootora_pvp_stats set rating=rating+16,wins=wins+1,updated_at=now() where user_id=v_opponent;
  end if;
  select coalesce(s.username,'Охотник') into v_username from public.lootora_clicker_saves s where s.user_id=v_opponent;
  return jsonb_build_object('status','matched','match_id',v_match_id,'won',v_winner=v_uid,'opponent',coalesce(v_username,'Охотник'),'rating_change',case when v_winner=v_uid then 16 else -16 end);
end;
$$;

revoke all on function public.lootora_create_guild(text,text) from public;
revoke all on function public.lootora_join_guild(bigint) from public;
revoke all on function public.lootora_leave_guild() from public;
revoke all on function public.lootora_disband_guild() from public;
revoke all on function public.lootora_pvp_join_queue() from public;
grant execute on function public.lootora_create_guild(text,text), public.lootora_join_guild(bigint), public.lootora_leave_guild(), public.lootora_disband_guild(), public.lootora_pvp_join_queue() to authenticated;
